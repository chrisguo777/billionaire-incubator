const assert = require('node:assert/strict');
const { registerHooks } = require('node:module');
const { existsSync } = require('node:fs');
const { fileURLToPath } = require('node:url');
registerHooks({resolve(s,c,next){if(s.startsWith('.')&&c.parentURL){const u=new URL(s+'.ts',c.parentURL);if(existsSync(fileURLToPath(u)))return next(u.href,c);}return next(s,c);}});
(async()=>{
 const {pickRetryGap}=await import('../lib/interview-round.ts');
 const req=(id,text=id)=>({id,text,priority:'high',kind:'must_have',keywords:[]});
 const requirements=[req('a'),req('b'),req('c'),req('d'),req('e','Bachelor degree required')];
 const jd={requirements};
 const gaps=requirements.map(r=>({requirement_id:r.id,status:'weak',reason:'missing details',evidence_fact_ids:[],related_card_ids:[]}));
 const turn=id=>({kind:'gap',requirement:{id},question:'Example question?',answer:'Real answer'});
 const old=[turn('a'),turn('b'),turn('c')];
 const snapshot=JSON.stringify({gaps,old});
 assert.equal(pickRetryGap(gaps,jd,{a:'has',b:'has',c:'has'},old,3).requirement_id,'d','prefer a new requirement');
 assert.equal(pickRetryGap(gaps,jd,{d:'none'},old,3).requirement_id,'a','respect explicit none, allow other angle on an older requirement');
 const ongoing=[...old,turn('d'),turn('a')];
 assert.equal(pickRetryGap(gaps,jd,{},ongoing,3).requirement_id,'b','never pick same requirement twice in current round');
 assert.equal(pickRetryGap(gaps,jd,{a:'none',b:'none',c:'none',d:'none'},old,3),null,'no fabricated educational or denied alternative');
 assert.equal(pickRetryGap(gaps.map(g=>({...g,status:'covered'})),jd,{},old,3).requirement_id,'d','new angle may supplement an already covered requirement');
 assert.equal(pickRetryGap(gaps.map(g=>({...g,status:'true_gap'})),jd,{},old,3),null);
 assert.equal(JSON.stringify({gaps,old}),snapshot,'selection must not modify records/history');
 process.env.LLM_MODE='mock';
 const {askQuestion}=await import('../lib/pipeline.ts');
 const db={cards:[],affiliations:[],education:[]};
 const first=await askQuestion(db,gaps[0],requirements[0],old,'zh',true);
 const second=await askQuestion(db,gaps[0],requirements[0],[...old,turn('d')],'zh',true);
 assert.notEqual(first,second);
 console.log('PASS: new topics, per-round exclusions, preserved history, explicit denials, education exclusion, exhausted topics, and mock alternatives; zero API calls.');
})().catch(e=>{console.error(e);process.exitCode=1});
