// Node 24+, deterministic review and export checks; no paid API calls.
const assert = require('node:assert/strict');
const { registerHooks } = require('node:module');
const { existsSync } = require('node:fs');
const { fileURLToPath } = require('node:url');
registerHooks({ resolve(specifier, context, next) {
  if (specifier.startsWith('.') && context.parentURL) {
    const url = new URL(specifier + '.ts', context.parentURL);
    if (existsSync(fileURLToPath(url))) return next(url.href, context);
  }
  return next(specifier, context);
} });
process.env.LLM_MODE = 'mock';
(async () => {
  const { beginFactReview, confirmFacts, changeFact, deleteAffiliation, addEducation, addExperience, reviewFacts } = await import('../lib/fact-review.ts');
  const { parseCV, analyzeJD, rewriteBullets, ensureOriginalBullets, checkBullet, parsedExperienceName } = await import('../lib/pipeline.ts');
  const { reviewResume } = await import('../lib/review.ts');
  const { bulletKey } = await import('../lib/review-types.ts');
  const affiliation = { title: 'Research Assistant', title_is_position: true, organization: 'Example University' };
  const fullName = 'Research Assistant · Example University';
  const responsibility = 'Cleaned and analyzed 500K+ healthcare records using R.';
  assert.equal(parsedExperienceName('Research Assistant', affiliation, []), fullName);
  assert.equal(parsedExperienceName(responsibility, affiliation, [responsibility]), fullName);
  assert.equal(parsedExperienceName('Maternal Health Study', affiliation, [responsibility]), 'Maternal Health Study');
  assert.equal(parsedExperienceName(fullName, affiliation, []), fullName);
  assert.equal(parsedExperienceName('Research Assistant', {...affiliation, organization: ''}, []), 'Research Assistant');
  assert.equal(parsedExperienceName('Healthcare data analysis', {...affiliation, title: null, title_is_position: false}, []), 'Healthcare data analysis');
  assert.throws(() => parsedExperienceName(responsibility, {...affiliation, title: null, title_is_position: false}, [responsibility]));
  const raw = await parseCV('ignored in mock');
  const multi = structuredClone(raw);
  multi.cards.push({ ...structuredClone(multi.cards[0]), id: 'extra-card' });
  const multiSnapshot = JSON.stringify(multi);
  const removedAffiliation = multi.affiliations[0].id;
  const removedCardIds = multi.cards.filter(c => c.affiliation_id === removedAffiliation).map(c => c.id);
  const withoutAffiliation = deleteAffiliation(multi, removedAffiliation);
  assert(!withoutAffiliation.affiliations.some(a => a.id === removedAffiliation));
  assert(!withoutAffiliation.cards.some(c => removedCardIds.includes(c.id)));
  assert(withoutAffiliation.cards.every(c => withoutAffiliation.affiliations.some(a => a.id === c.affiliation_id)));
  assert.deepEqual(withoutAffiliation.cards, multi.cards.filter(c => c.affiliation_id !== removedAffiliation));
  assert.deepEqual(withoutAffiliation.education, multi.education);
  assert.deepEqual(withoutAffiliation.header, multi.header);
  assert.equal(JSON.stringify(multi), multiSnapshot, 'delete must preserve the snapshot used for undo');
  assert.equal(deleteAffiliation(multi, 'missing'), multi);
  let empty = multi;
  for (const affiliation of multi.affiliations) empty = deleteAffiliation(empty, affiliation.id);
  assert.equal(empty.cards.length, 0);
  assert.equal(empty.affiliations.length, 0);
  const schoolDraft = { school: ' Example University ', degree: 'M.S.', field: 'Statistics', location: null, start_date: null, end_date: '2026', gpa: null, details: [' Scholarship ', ''] };
  assert.throws(() => addEducation(raw, { ...schoolDraft, school: '  ' }));
  const withSchool = addEducation(raw, schoolDraft);
  assert.equal(withSchool.education.at(-1).school, 'Example University');
  assert.deepEqual(withSchool.education.at(-1).details, ['Scholarship']);
  assert.deepEqual(withSchool.cards, raw.cards);
  const manualDraft = { name: 'Community survey project', organization: 'Example Community Lab', title: 'Volunteer Analyst', type: 'volunteer', start_date: '2025', end_date: '2026', actions: ['Prepared survey summaries', ''], outcomes: ['Shared findings with organizers'] };
  assert.throws(() => addExperience(raw, { ...manualDraft, name: ' ' }));
  assert.throws(() => addExperience(raw, { ...manualDraft, actions: [' '] }));
  let withManual = addExperience(withSchool, manualDraft);
  const manualCard = withManual.cards.at(-1);
  assert.equal(manualCard.name, manualDraft.name);
  assert.equal(withManual.affiliations.at(-1).type, 'volunteer');
  assert.deepEqual(manualCard.original_bullets, []);
  assert.equal(manualCard.my_actions[0].source, 'user_edit');
  assert.equal(manualCard.my_actions[0].status, 'ai_inferred');
  assert.equal(manualCard.outcomes[0].status, 'ai_inferred');
  const withAnother = addExperience(addEducation(withManual, schoolDraft), manualDraft);
  const allIds = [...withAnother.education, ...withAnother.affiliations, ...withAnother.cards, ...reviewFacts(withAnother)].map(x => x.id);
  assert.equal(new Set(allIds).size, allIds.length, 'repeated additions must use distinct ids');
  const manualJd = await analyzeJD('ignored');
  const beforeConfirmation = await rewriteBullets(withManual, manualJd, [manualCard.id]);
  assert.equal(beforeConfirmation[0].bullets.length, 0, 'unconfirmed new experiences cannot produce usable suggestions');
  withManual = confirmFacts(withManual, reviewFacts(withManual).map(f => f.id));
  const manualRewrites = await rewriteBullets(withManual, manualJd, [manualCard.id]);
  assert(manualRewrites[0].bullets.length > 0);
  const manualChoices = {};
  manualRewrites[0].bullets.forEach((b, i) => { manualChoices[bulletKey(manualCard.id, i, b.original_bullet_id, b.source_ids)] = { text: b.text, status: 'accepted' }; });
  const manualResume = reviewResume(withManual, manualJd, [], manualRewrites, manualChoices, 'relevance', [manualCard.id]).resume;
  assert(manualResume.markdown.includes('Example University'));
  assert(manualResume.markdown.includes('Prepared survey summaries'));
  const removedManual = deleteAffiliation(withManual, manualCard.affiliation_id);
  assert(!removedManual.cards.some(c => c.id === manualCard.id));
  assert.equal(removedManual.education.length, withManual.education.length);
  const bulkCard = { ...structuredClone(raw.cards[0]), id: 'bulk-card', original_bullets: [] };
  for (const key of ['context','my_actions','team_actions','methods','tools','skills','scale','outcomes']) bulkCard[key] = [];
  bulkCard.my_actions = Array.from({length:10},(_,i)=>({id:'bulk-f'+i,text:'Reviewed source '+String.fromCharCode(65+i),status:'ai_inferred',source:'user_edit'}));
  const bulkDB = { ...raw, cards:[bulkCard,structuredClone(raw.cards[1])] };
  const nineIds = bulkCard.my_actions.slice(0,9).map(f=>f.id);
  const verifiedNine = confirmFacts(bulkDB,nineIds);
  assert.equal(verifiedNine.cards[0].my_actions.filter(f=>f.status==='user_confirmed').length,9);
  assert.equal(verifiedNine.cards[0].my_actions[9].status,'ai_inferred','deselected tenth fact must stay pending');
  assert.deepEqual(verifiedNine.cards[1],bulkDB.cards[1],'per-experience confirmation must not change another experience');
  assert.equal(checkBullet(verifiedNine,bulkCard.my_actions[9].text,[bulkCard.my_actions[9].id],bulkCard.id).ok,false);
  const correctedTenth = changeFact(verifiedNine,bulkCard.my_actions[9].id,{...bulkCard.my_actions[9],text:'Reviewed corrected source'});
  assert.equal(correctedTenth.cards[0].my_actions[9].status,'ai_inferred');
  assert.equal(correctedTenth.cards[0].my_actions.filter(f=>f.status==='user_confirmed').length,9);
  const allTen = confirmFacts(correctedTenth,[bulkCard.my_actions[9].id]);
  assert.equal(allTen.cards[0].my_actions.filter(f=>f.status==='user_confirmed').length,10);
  assert(bulkDB.cards[0].my_actions.every(f=>f.status==='ai_inferred'),'bulk confirmation must not mutate the original');
  const snapshot = JSON.stringify(raw);
  const draft = beginFactReview(raw);
  assert(reviewFacts(draft).length > 0);
  assert(reviewFacts(draft).every(f => f.status === 'ai_inferred'));
  assert(reviewFacts(draft).every(f => f.source === 'cv_parse'));
  assert.equal(JSON.stringify(raw), snapshot, 'review preparation must not mutate the original');
  const fact = draft.cards[0].my_actions[0];
  const one = confirmFacts(draft, [fact.id]);
  assert.equal(reviewFacts(one).filter(f => f.status === 'user_confirmed').length, 1);
  assert.equal(reviewFacts(one).find(f => f.id === fact.id).source, 'cv_parse');
  const confirmed = confirmFacts(draft, reviewFacts(draft).map(f => f.id));
  assert(reviewFacts(confirmed).every(f => f.status === 'user_confirmed'));
  const edited = changeFact(confirmed, fact.id, { ...fact, text: 'Reviewed patient records with Python' });
  assert.equal(edited.cards[0].my_actions[0].status, 'ai_inferred');
  assert.equal(edited.cards[0].my_actions[0].source, 'user_edit');
  assert.deepEqual(edited.cards[0].original_bullets, []);
  assert.deepEqual(edited.cards[1], confirmed.cards[1], 'other experiences retain their exact originals');
  const deleted = changeFact(confirmed, fact.id, null);
  assert(!reviewFacts(deleted).some(f => f.id === fact.id));
  assert.deepEqual((await ensureOriginalBullets(deleted, 'old CV')).cards[0].original_bullets, [], 'deleted originals must not be reparsed');
  const shared = structuredClone(confirmed);
  shared.cards[1].original_bullets.push(shared.cards[0].original_bullets[0]);
  const sharedOriginal = shared.cards[0].original_bullets[0].id;
  const sharedDeleted = changeFact(shared, fact.id, null);
  assert(!sharedDeleted.cards.some(c => c.original_bullets.some(b => b.id === sharedOriginal)), 'shared source blocks must not restore deleted content through a sibling card');
  const outcome = confirmed.cards[0].outcomes[0];
  const correctedOutcome = changeFact(confirmed, outcome.id, { ...outcome, value: 0.75, unit: 'AUC', basis: 'validation set' });
  assert.equal(correctedOutcome.cards[0].outcomes[0].value, 0.75);
  assert.equal(correctedOutcome.cards[0].outcomes[0].status, 'ai_inferred');
  // A distinct removed claim must not return through untouched-original fallback.
  const changed = confirmFacts(edited, [fact.id]);
  const jd = await analyzeJD('ignored');
  const rewritten = await rewriteBullets(changed, jd, [changed.cards[0].id]);
  assert(rewritten[0].bullets.length > 0, 'corrected cards still produce reviewable suggestions');
  assert(rewritten[0].bullets.every(b => b.original_bullet_id === null));
  const pending = reviewResume(changed, jd, [], rewritten, {}, 'relevance', [changed.cards[0].id]);
  assert.equal(pending.resume.experienceBulletCount, 0, 'new suggestions require explicit acceptance');
  const choices = {};
  rewritten[0].bullets.forEach((b, i) => { choices[bulletKey(changed.cards[0].id, i, b.original_bullet_id, b.source_ids)] = { text: b.text, status: 'accepted' }; });
  const accepted = reviewResume(changed, jd, [], rewritten, choices, 'relevance', [changed.cards[0].id]);
  assert(accepted.resume.markdown.includes('Reviewed patient records with Python'));
  assert(!accepted.resume.markdown.includes('Built logistic regression models'));
  assert.equal(JSON.stringify(raw), snapshot);
  console.log('PASS: pending states, explicit confirmation, immutable edits/deletion, structured outcomes, no stale-original restoration, and accepted-only export');
})().catch(e => { console.error(e); process.exitCode = 1; });
